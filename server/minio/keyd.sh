#!/bin/bash
# minio-keyd: creates and removes the per-Mac MinIO object keys.
#
# Each approved Mac gets its own MinIO service account, named
# mac-<12 hex>-<gen>, whose parent is the user jm-macs (canned policy
# jm-client: Get/Put/List, no Delete). Revoking a Mac removes its service
# account, so a revoked Mac's stored key stops working at MinIO.
#
# The Manager never holds a MinIO admin credential. It writes the keys it
# wants into a shared directory; this daemon, holding only the scoped
# jm-keyadmin user, makes MinIO match, and reports what MinIO says.
#
# Files in $JM_OBJKEYS_DIR (mode 0700; every file written atomically, 0600).
# KEYD_PROTOCOL.md (beside this script) is the contract with the Manager:
#   desired.json        Manager -> keyd. No secrets.
#     {"seq":N,"keys":[{"name":"mac-4f1c2a9e7b3d-1","state":"active"}, ...]}
#     optional: "allow_mass_delete":N (equal to seq to confirm a mass
#     delete), "remove":["name",...] (explicit named deletion authority),
#     per key "needs_secret":true (re-create a key whose secret
#     was lost before delivery). "keys":null means no keys. Other members
#     are allowed if their value is a string, number, true, false or null.
#     keyd parses it with a strict JSON tokenizer: a syntax error, a member
#     twice in one object, a member name that is not [A-Za-z0-9_] (or that
#     differs only in case from a field keyd reads), or an escape sequence
#     in a field keyd reads refuses the whole file.
#   results/<name>.json keyd -> Manager, one per key created:
#     {"name":"...","secret_key":"...","created_ms":N}
#     The Manager stores the secret, clears needs_secret for the key in
#     desired.json, and only then deletes the file.
#   applied.json        keyd -> Manager. No secrets. Built from what MinIO
#     reports (`svcacct ls` and `svcacct info`), never from desired.json:
#     {"seq":N,"verified_ms":N,"error":"...","keys":[{"name":"...",
#      "exists":true,"status":"on","parent":"jm-macs","implied_policy":true}]}
#   keyd-created-seq    keyd only. "<name> <seq>[ p|c]" per line: the desired
#     seq at which keyd last created each key; p = its result is waiting for
#     the Manager; c = the Manager took the result while needs_secret was
#     still set, so needs_secret is ignored for that key until a desired.json
#     without it is seen (a stale flag must not kill a delivered secret).
#     needs_secret is honoured only when the desired seq is higher than the
#     recorded one, so one request re-creates a key once.
#   .keyd-mc            keyd only: the reply of the running mc call (for
#     svcacct add it holds the new secret until results/ has it).
#
# Rules, all fail-closed:
#   - A desired.json with any name not matching NAME_RE, a duplicate name,
#     a state other than "active", or a "parent" other than jm-macs is
#     refused as a whole: nothing is created or removed.
#   - A desired.json whose seq is lower than the last applied seq is refused.
#   - No desired.json means "no instruction", never "remove everything".
#   - The parent is hard-coded; no input can mint a key under jm-client,
#     jm-gc or any other user. A key is removed only if MinIO reports its
#     parent as jm-macs.
#   - Only names in remove may be deleted. A live name omitted from both
#     keys and remove is preserved and reported as an unobserved orphan.
#   - Mass-delete guard: removing more than MASS_MAX keys, or more than one
#     key and more than MASS_PCT% of the keys, needs "allow_mass_delete"
#     equal to seq. An empty or reset Manager store must not cut off
#     every Mac.
#   - Secrets are generated by MinIO (svcacct add without --secret-key), so
#     no secret is ever on a command line. They are written only to
#     results/, never to a log.
#   - TERM or INT while a key is being created waits until its result is
#     written (or the undeliverable key removed), so a stop never strands
#     a key whose secret nobody has. The wait is bounded: after
#     JM_KEYD_HOLD_MAX seconds (default 50, below the compose
#     stop_grace_period of 60 s) keyd kills the stuck mc, removes the key if
#     MinIO made it (5 s more at most), logs GAVE UP, and exits.
#
# What the credential does NOT enforce. jm-keyadmin may create, remove and
# list service accounts (jm-keyadmin-policy.json; no update, so it cannot
# reset another account's secret). That keyd mints only under jm-macs, and
# that a keyd key cannot delete objects, is enforced by this script (the
# hard-coded parent and the name check), not by the credential: MinIO's
# AddServiceAccount accepts any non-root target user (design A7, read in
# the 2021 source), so a stolen jm-keyadmin secret could mint a key under
# jm-gc, which can delete. Residual, verify on the pinned MinIO release:
# whether jm-keyadmin can target jm-gc, and whether svcacct info needs
# more than ListServiceAccounts.
#
# Environment:
#   JM_OBJ_PER_MAC_SERVER       1 = run; 0 or unset = idle; anything else
#                               is reported and keyd idles. (Rollout step
#                               M1. The Manager's JM_OBJ_PER_MAC is M2.)
#   JM_OBJ_KEYADMIN_ACCESS_KEY  default jm-keyadmin
#   JM_OBJ_KEYADMIN_SECRET_KEY  required, 32-40 chars [A-Za-z0-9]
#   JM_MINIO_ENDPOINT           default http://127.0.0.1:9000
#   JM_OBJKEYS_DIR              default /var/lib/jm-objkeys
#   JM_KEYD_INTERVAL            seconds between cycles, default 2
#   JM_KEYD_ONCE                1 = run one cycle and exit (tests)
#   JM_KEYD_HOLD_MAX            seconds a stop waits for a key create,
#                               default 50 (tests set it lower)
#   MC                          default mc
#
# Uses bash builtins, mc, and coreutils mkdir/chmod/mv/rm/date/sleep only
# (the minio image is ubi-micro). keyd refuses to start with the MinIO root
# password or an object-key secret in its environment.
set -u
set -f # no pathname expansion of names read from files or mc
# Bytes, not characters: in a UTF-8 locale bash indexes strings from the
# start on every ${s:i:n}, which made the parser quadratic (32 s for 300
# indented keys), and [[:space:]] matched non-JSON whitespace.
LC_ALL=C

MC="${MC:-mc}"
PARENT=jm-macs
NAME_RE='^mac-[0-9a-f]{12}-[1-9][0-9]{0,2}$'
MASS_MAX=3
MASS_PCT=25
KA_AK="${JM_OBJ_KEYADMIN_ACCESS_KEY:-jm-keyadmin}"
KA_SK="${JM_OBJ_KEYADMIN_SECRET_KEY:-}"
ENDPOINT="${JM_MINIO_ENDPOINT:-http://127.0.0.1:9000}"
DIR="${JM_OBJKEYS_DIR:-/var/lib/jm-objkeys}"
INTERVAL="${JM_KEYD_INTERVAL:-2}"
ONCE="${JM_KEYD_ONCE:-0}"
HOLD_MAX="${JM_KEYD_HOLD_MAX:-50}"
ALIAS=jmkeyd

log() { echo "[keyd] $*" >&2; }
die() {
	log "$*"
	exit 2
}

case "${JM_OBJ_PER_MAC_SERVER:-}" in
1) PER_MAC_SERVER=1 ;;
0 | '') PER_MAC_SERVER=0 ;;
*)
	PER_MAC_SERVER=0
	log "ERROR: JM_OBJ_PER_MAC_SERVER='${JM_OBJ_PER_MAC_SERVER//[^A-Za-z0-9 ]/?}' is not 1 or 0; per-Mac object keys stay off"
	;;
esac
if [ "$PER_MAC_SERVER" != 1 ]; then
	log "per-Mac object keys are off (JM_OBJ_PER_MAC_SERVER is not 1); idle"
	[ "$ONCE" = 1 ] && exit 0
	trap 'exit 0' TERM INT
	while :; do
		sleep 3600 &
		wait $! 2>/dev/null || true
	done
fi

# keyd holds jm-keyadmin and nothing else.
for v in MINIO_ROOT_PASSWORD JM_OBJ_GC_SECRET_KEY JM_OBJ_CLIENT_SECRET_KEY; do
	[ -z "${!v:-}" ] || die "refusing to run with $v in the environment; keyd holds only the key admin credential"
done
[[ "$KA_SK" =~ ^[A-Za-z0-9]{32,40}$ ]] || die "JM_OBJ_KEYADMIN_SECRET_KEY must be 32-40 characters of A-Z a-z 0-9"
[[ "$KA_AK" =~ ^[a-z0-9-]{3,20}$ ]] || die "access key '$KA_AK' must be 3-20 characters of a-z 0-9 -"
case "$KA_AK" in
"$PARENT" | jm-client | jm-gc | juicemount | "${MINIO_ROOT_USER:-juicemount}") die "the key admin must not be '$KA_AK'" ;;
esac
[[ "$INTERVAL" =~ ^[1-9][0-9]{0,3}$ ]] || die "JM_KEYD_INTERVAL must be a whole number of seconds"
[[ "$HOLD_MAX" =~ ^[1-9][0-9]?$ ]] || die "JM_KEYD_HOLD_MAX must be 1-99 seconds"

urlenc() {
	local s="$1" out='' c i
	for ((i = 0; i < ${#s}; i++)); do
		c="${s:i:1}"
		case "$c" in
		[A-Za-z0-9._~-]) out+="$c" ;;
		*) out+="$(printf '%%%02x' "'$c")" ;;
		esac
	done
	printf '%s' "$out"
}
[[ "$ENDPOINT" =~ ^(https?)://(.+)$ ]] || die "JM_MINIO_ENDPOINT must start with http:// or https://"
export MC_HOST_jmkeyd="${BASH_REMATCH[1]}://$(urlenc "$KA_AK"):$(urlenc "$KA_SK")@${BASH_REMATCH[2]}"
KA_SK=''
unset JM_OBJ_KEYADMIN_SECRET_KEY
export MC_CONFIG_DIR="${TMPDIR:-/tmp}/jm-keyd-mc-$$"
MC_TMP="$DIR/.keyd-mc"
trap 'rm -rf "$MC_CONFIG_DIR"; rm -f "$MC_TMP"' EXIT

# A stop that arrives while a key is being created is held until its
# secret is in results/, for HOLD_MAX seconds at most. mc runs in the
# background and keyd waits with the wait builtin, which a signal
# interrupts, so the stop is seen at once and the bound can be enforced.
HOLD=0
STOP=0
STOP_DEADLINE=0
GAVE_UP=0
MC_PID=''
TIMER_PID=''
# arm_timer: kill the running mc at STOP_DEADLINE.
arm_timer() {
	local left=$((STOP_DEADLINE - SECONDS)) pid="$MC_PID"
	[ "$left" -gt 0 ] || left=0
	(
		trap 'kill "$s" 2>/dev/null; exit 0' TERM
		sleep "$left" &
		s=$!
		wait "$s"
		kill -TERM "$pid" 2>/dev/null
	) >/dev/null 2>&1 &
	TIMER_PID=$!
}
on_stop() {
	if [ "$HOLD" = 1 ]; then
		if [ "$STOP" != 1 ]; then
			STOP=1
			STOP_DEADLINE=$((SECONDS + HOLD_MAX))
			log "stop requested while creating a key; stopping after its result is written (at most ${HOLD_MAX}s)"
			[ -n "$MC_PID" ] && arm_timer
		fi
		return 0
	fi
	exit 0
}
hold() { HOLD=1; }
release() {
	HOLD=0
	if [ "$STOP" = 1 ]; then
		log "stopping: the key being created was finished first"
		exit 0
	fi
}
trap on_stop TERM INT

# mcq args...: run mc; MC_OUT = its output (stdout and stderr), status = mc's.
mcq() {
	local rc
	MC_OUT=''
	"$MC" "$@" >"$MC_TMP" 2>&1 &
	MC_PID=$!
	[ "$STOP" = 1 ] && arm_timer
	while :; do
		wait "$MC_PID"
		rc=$?
		[ "$rc" -le 128 ] && break
		kill -0 "$MC_PID" 2>/dev/null && continue # a signal interrupted wait
		wait "$MC_PID"                           # mc ended meanwhile: its status
		rc=$?
		break
	done
	if [ -n "$TIMER_PID" ]; then
		kill "$TIMER_PID" 2>/dev/null
		TIMER_PID=''
	fi
	MC_PID=''
	if [ "$STOP" = 1 ] && [ "$rc" -ne 0 ] && [ "$SECONDS" -ge "$STOP_DEADLINE" ]; then
		GAVE_UP=1
	fi
	[ -f "$MC_TMP" ] && MC_OUT="$(<"$MC_TMP")"
	rm -f "$MC_TMP"
	return "$rc"
}

umask 077
mkdir -p "$DIR/results" || die "cannot create $DIR/results"
chmod 0700 "$DIR" "$DIR/results" || die "cannot set mode 0700 on $DIR"
[ -d "$MC_TMP" ] && die "$MC_TMP is a directory; remove it"
rm -f "$MC_TMP"

# mc --json reply patterns. Values keyd uses from mc never contain quotes.
RE_AK='"accessKey"[[:space:]]*:[[:space:]]*"([^"]*)"'
RE_SK='"secretKey"[[:space:]]*:[[:space:]]*"([^"]*)"'
RE_PARENT_USER='"parentUser"[[:space:]]*:[[:space:]]*"([^"]*)"'
RE_ACCT_STATUS='"accountStatus"[[:space:]]*:[[:space:]]*"([^"]*)"'
RE_IMPLIED='"impliedPolicy"[[:space:]]*:[[:space:]]*true'
RE_MC_ERROR='"status"[[:space:]]*:[[:space:]]*"error"'
RE_MC_MSG='"message"[[:space:]]*:[[:space:]]*"([^"]*)"'
RE_SEQ='"seq"[[:space:]]*:[[:space:]]*([0-9]{1,15})[[:space:]]*([,}]|$)'

nl=$'\n'
has() { case "$nl$1" in *"$nl$2$nl"*) return 0 ;; esac; return 1; }
count() {
	local n=0 x
	for x in $1; do n=$((n + 1)); done
	echo "$n"
}
mc_msg() { [[ "$1" =~ $RE_MC_MSG ]] && printf '%s' "${BASH_REMATCH[1]//\\/}" || printf 'no detail'; }
now_ms() { printf '%s000' "$(date +%s)"; }

# write_atomic file content: 0 on success, else WA_ERR + 1. A directory at
# the target name is refused: mv would move the file into it and report
# success, so the write would be lost silently.
write_atomic() {
	local tmp="$1.tmp.$$"
	WA_ERR=''
	if [ -d "$1" ]; then
		WA_ERR="${1##*/} is a directory"
		log "cannot write $1: it is a directory"
		return 1
	fi
	printf '%s\n' "$2" >"$tmp" && chmod 0600 "$tmp" && mv -f "$tmp" "$1" && return 0
	rm -f "$tmp"
	WA_ERR="cannot write ${1##*/}"
	return 1
}

# list_keys: EXISTING = every access key MinIO lists under jm-macs.
list_keys() {
	local out rest
	mcq --json admin user svcacct ls "$ALIAS" "$PARENT"
	local rc=$?
	out="$MC_OUT"
	if [ "$rc" -ne 0 ] || [[ "$out" =~ $RE_MC_ERROR ]]; then
		log "svcacct ls $PARENT failed: $(mc_msg "$out")"
		return 1
	fi
	EXISTING=''
	rest="$out"
	while [[ "$rest" =~ $RE_AK ]]; do
		EXISTING+="${BASH_REMATCH[1]}$nl"
		rest="${rest#*"${BASH_REMATCH[0]}"}"
	done
	MANAGED=''
	local k
	for k in $EXISTING; do
		[[ "$k" =~ $NAME_RE ]] && MANAGED+="$k$nl"
	done
	return 0
}

# key_info name: I_PARENT, I_STATUS, I_IMPLIED as MinIO reports them.
key_info() {
	local out rc
	I_PARENT=''
	I_STATUS=''
	I_IMPLIED=false
	mcq --json admin user svcacct info "$ALIAS" "$1"
	rc=$?
	out="$MC_OUT"
	if [ "$rc" -ne 0 ] || [[ "$out" =~ $RE_MC_ERROR ]]; then
		log "svcacct info $1 failed: $(mc_msg "$out")"
		return 1
	fi
	[[ "$out" =~ $RE_PARENT_USER ]] && I_PARENT="${BASH_REMATCH[1]}"
	[[ "$out" =~ $RE_ACCT_STATUS ]] && I_STATUS="${BASH_REMATCH[1]}"
	[[ "$out" =~ $RE_IMPLIED ]] && I_IMPLIED=true
	return 0
}

# remove_key name: remove. Only a key MinIO reports under jm-macs is
# touched. There is no disable step first: jm-keyadmin has no
# UpdateServiceAccount (it would let the credential reset any account's
# secret), and rm takes effect at once anyway.
remove_key() {
	local name="$1"
	if ! key_info "$name"; then
		log "not removing $name: its parent could not be verified"
		return 1
	fi
	if [ "$I_PARENT" != "$PARENT" ]; then
		log "REFUSED removing $name: MinIO reports parent '$I_PARENT', not $PARENT"
		return 1
	fi
	if ! mcq --json admin user svcacct rm "$ALIAS" "$name"; then
		log "svcacct rm $name failed: $(mc_msg "$MC_OUT")"
		return 1
	fi
	log "removed $name"
	return 0
}

# create_key name: MinIO generates the secret; it goes to results/<name>.json.
# The whole create is held against a stop (see on_stop), on every path that
# creates a key, so no caller can forget it.
create_key() {
	hold
	create_key_held "$1"
	local rc=$?
	release
	return "$rc"
}
create_key_held() {
	local name="$1" out sk='' ak='' rc
	mcq --json admin user svcacct add "$ALIAS" "$PARENT" --access-key "$name"
	rc=$?
	out="$MC_OUT"
	MC_OUT=''
	if [ "$GAVE_UP" = 1 ]; then
		out=''
		log "ERROR: GAVE UP waiting ${HOLD_MAX}s for svcacct add $name during a stop; removing the key if MinIO made it. If it stays, the Manager must set needs_secret for it and raise seq (KEYD_PROTOCOL.md)"
		STOP_DEADLINE=$((SECONDS + 5))
		remove_key "$name"
		return 1
	fi
	if [ "$rc" -ne 0 ] || [[ "$out" =~ $RE_MC_ERROR ]]; then
		log "svcacct add $name failed: $(mc_msg "$out")"
		return 1
	fi
	[[ "$out" =~ $RE_SK ]] && sk="${BASH_REMATCH[1]}"
	[[ "$out" =~ $RE_AK ]] && ak="${BASH_REMATCH[1]}"
	out=''
	if [ "$ak" != "$name" ] || ! [[ "$sk" =~ ^[A-Za-z0-9+/]{32,40}$ ]]; then
		sk=''
		log "svcacct add $name: reply has no usable access key and secret; removing the undeliverable key"
		remove_key "$name"
		return 1
	fi
	if ! write_atomic "$DIR/results/$name.json" "{\"name\":\"$name\",\"secret_key\":\"$sk\",\"created_ms\":$(now_ms)}"; then
		sk=''
		log "cannot write results/$name.json ($WA_ERR); removing the undeliverable key"
		CREATE_ERR="results/$name.json: $WA_ERR"
		remove_key "$name"
		return 1
	fi
	sk=''
	set_flag "$name" p
	log "created $name"
	return 0
}

# --- desired.json parser ------------------------------------------------
# parse_desired text: D_SEQ, D_ALLOW, D_NAMES, D_NEEDS, or D_ERR + return 1.
# One pass of a strict JSON tokenizer that reads the fields as it goes, so
# what keyd acts on is what a JSON decoder reads. Tokens are matched in a
# 4 KiB window at offset JP (a token longer than that is refused). The
# result is cached with the text, so an unchanged desired.json costs one
# string compare per cycle; only an accepted text is cached.
J_WS='[ '$'\t\n\r'']*'
# [:cntrl:] in the C locale is 0x00-0x1f and 0x7f: a raw DEL in a string is
# refused although JSON allows it (bash cannot hold \001 in a pattern).
J_STR='"([^"\\[:cntrl:]]|\\["\\/bfnrt]|\\u[0-9A-Fa-f]{4})*"'
J_NUM='-?(0|[1-9][0-9]*)([.][0-9]+)?([eE][+-]?[0-9]+)?'
RE_TOK="^$J_WS([][{}:,]|$J_STR|$J_NUM|true|false|null)"
RE_BLANK="^$J_WS\$"
RE_MEMBER='^"[A-Za-z0-9_]{1,64}"$'
RE_UINT='^(0|[1-9][0-9]{0,14})$'
PD_TEXT='' # the last accepted text, and its result:
PD_SEQ=''
PD_ALLOW=''
PD_NAMES=''
PD_NEEDS=''
PD_REMOVE=''
jv_next() {
	local w="${JV:JP:4096}"
	if [[ "$w" =~ $RE_TOK ]]; then
		JT="${BASH_REMATCH[1]}"
		JP=$((JP + ${#BASH_REMATCH[0]}))
		return 0
	fi
	JT=''
	if [[ "$w" =~ $RE_BLANK ]]; then
		JV_ERR='unexpected end of file'
	elif [[ "$w" =~ ^$J_WS\" ]]; then
		JV_ERR='a string has a raw control character or a bad escape, or is over 4 KiB'
	else
		JV_ERR='not valid JSON'
	fi
	return 1
}
jv_scalar() {
	case "$JT" in
	'{' | '[' | '}' | ']' | ':' | ',') return 1 ;;
	esac
	return 0
}
# jv_member: JT is the member name token. K = the name, or JV_ERR + 1.
jv_member() {
	local f=0
	if ! [[ "$JT" =~ $RE_MEMBER ]]; then
		case "$JT" in
		*\\*) JV_ERR='escape sequences are not allowed in member names' ;;
		\"*) JV_ERR='a member name is not 1-64 of A-Z a-z 0-9 _' ;;
		*) JV_ERR='expected a member name' ;;
		esac
		return 1
	fi
	K="${JT:1:${#JT}-2}"
	# A JSON decoder may match member names without regard to case (Go
	# does), so a case variant of a field keyd reads is refused.
	shopt -s nocasematch
	case "$K" in seq | keys | remove | allow_mass_delete | parent | name | state | needs_secret) f=1 ;; esac
	shopt -u nocasematch
	if [ "$f" = 1 ]; then
		case "$K" in
			seq | keys | remove | allow_mass_delete | parent | name | state | needs_secret) ;;
		*)
			JV_ERR="member ${K} differs only in case from a field keyd reads"
			return 1
			;;
		esac
	fi
	return 0
}
# jv_str field: JT must be a string without escapes; V = its text.
jv_str() {
	case "$JT" in
	\"*\\*)
		JV_ERR="escape sequences are not allowed in $1"
		return 1
		;;
	\"*) V="${JT:1:${#JT}-2}" ;;
	*)
		JV_ERR="$1 is not a string"
		return 1
		;;
	esac
}
# jv_uint field: JT must be a whole number of at most 15 digits.
jv_uint() {
	if ! [[ "$JT" =~ $RE_UINT ]]; then
		JV_ERR="$1 is not a whole number of at most 15 digits"
		return 1
	fi
}
# jv_object top|entry: the members of an object whose "{" was just read.
# Sets JV_SEM for errors in content (bad name, state, parent) as opposed
# to syntax.
jv_object() {
	local seen="$nl" e_name='' e_state='' e_needs=0
	jv_next || return 1
	if [ "$JT" != '}' ]; then
		while :; do
			jv_member || return 1
			if has "$seen" "$K"; then
				JV_ERR="duplicate member $K"
				return 1
			fi
			seen+="$K$nl"
			jv_next || return 1
			if [ "$JT" != : ]; then
				JV_ERR='expected :'
				return 1
			fi
			jv_next || return 1
			case "$1:$K" in
				top:keys)
				HAVE_KEYS=1
				if [ "$JT" = '[' ]; then
					jv_keys || return 1
				elif [ "$JT" != null ]; then
					JV_ERR='keys is not an array or null'
					return 1
					fi
					;;
				top:remove)
				if [ "$JT" != '[' ]; then
					JV_ERR='remove is not an array'
					return 1
				fi
				jv_remove || return 1
				;;
			top:seq)
				jv_uint seq || return 1
				D_SEQ="$JT"
				;;
			top:allow_mass_delete)
				if [ "$JT" != null ]; then
					jv_uint allow_mass_delete || return 1
					D_ALLOW="$JT"
				fi
				;;
			top:parent | entry:parent)
				jv_str parent || return 1
				if [ "$V" != "$PARENT" ]; then
					JV_SEM="parent '${V//[^A-Za-z0-9-]/?}' is not $PARENT"
					return 1
				fi
				;;
			entry:name)
				jv_str name || return 1
				e_name="$V"
				;;
			entry:state)
				jv_str state || return 1
				e_state="$V"
				;;
			entry:needs_secret)
				case "$JT" in
				true) e_needs=1 ;;
				false | null) ;;
				*)
					JV_ERR='needs_secret is not true, false or null'
					return 1
					;;
				esac
				;;
			*)
				if ! jv_scalar; then
					JV_ERR="member $K is not a string, number, true, false or null"
					return 1
				fi
				;;
			esac
			jv_next || return 1
			case "$JT" in
			,) jv_next || return 1 ;;
			'}') break ;;
			*)
				JV_ERR='expected , or }'
				return 1
				;;
			esac
		done
	fi
	[ "$1" = entry ] || return 0
	if [ -z "$e_name" ]; then
		JV_SEM='an entry has no name'
		return 1
	fi
	if ! [[ "$e_name" =~ $NAME_RE ]]; then
		JV_SEM="name '${e_name//[^A-Za-z0-9-]/?}' does not match mac-<12 hex>-<1-999>"
		return 1
	fi
	if has "$D_NAMES" "$e_name"; then
		JV_SEM="duplicate name $e_name"
		return 1
	fi
	if [ "$e_state" != active ]; then
		JV_SEM="$e_name: state '${e_state//[^A-Za-z0-9-]/?}' is not active"
		return 1
	fi
	D_NAMES+="$e_name$nl"
	[ "$e_needs" = 1 ] && D_NEEDS+="$e_name$nl"
	return 0
}
jv_keys() { # the "[" of "keys" was just read
	jv_next || return 1
	[ "$JT" = ']' ] && return 0
	while :; do
		if [ "$JT" != '{' ]; then
			JV_ERR='a keys entry is not an object'
			return 1
		fi
		jv_object entry || return 1
		jv_next || return 1
		case "$JT" in
		,) jv_next || return 1 ;;
		']') return 0 ;;
		*)
			JV_ERR='expected , or ]'
			return 1
			;;
		esac
	done
}
jv_remove() { # explicit named removal authority; never inferred from keys
	jv_next || return 1
	[ "$JT" = ']' ] && return 0
	while :; do
		jv_str remove || return 1
		if ! [[ "$V" =~ $NAME_RE ]] || has "$D_REMOVE" "$V"; then
			JV_SEM="invalid or duplicate removal name '${V//[^A-Za-z0-9-]/?}'"
			return 1
		fi
		D_REMOVE+="$V$nl"
		jv_next || return 1
		case "$JT" in
		,) jv_next || return 1 ;;
		']') return 0 ;;
		*) JV_ERR='expected , or ] in remove'; return 1 ;;
		esac
	done
}
parse_desired() {
	D_ERR=''
	if [ -n "$PD_TEXT" ] && [ "$1" = "$PD_TEXT" ]; then
		D_SEQ="$PD_SEQ"
		D_ALLOW="$PD_ALLOW"
		D_NAMES="$PD_NAMES"
		D_NEEDS="$PD_NEEDS"
		D_REMOVE="$PD_REMOVE"
		return 0
	fi
	D_SEQ=''
	D_ALLOW=''
	D_NAMES=''
	D_NEEDS=''
	D_REMOVE=''
	JV="$1"
	JP=0
	JT=''
	JV_ERR=''
	JV_SEM=''
	HAVE_KEYS=0
	if ! { jv_next && [ "$JT" = '{' ]; }; then
		D_ERR="not strict JSON: ${JV_ERR:-not a JSON object}"
	elif ! jv_object top; then
		if [ -n "$JV_SEM" ]; then
			D_ERR="$JV_SEM"
		else
			D_ERR="not strict JSON: $JV_ERR"
		fi
	elif ! [[ "${JV:JP}" =~ $RE_BLANK ]]; then
		D_ERR='not strict JSON: data after the closing brace'
	elif [ -z "$D_SEQ" ]; then
		D_ERR='no numeric seq'
	elif [ "$HAVE_KEYS" != 1 ]; then
		D_ERR='no keys array'
	else
		local k
		for k in $D_REMOVE; do
			if has "$D_NAMES" "$k"; then
				D_ERR="name $k is both wanted and removed"
				break
			fi
		done
	fi
	JV=''
	if [ -n "$D_ERR" ]; then
		D_NAMES=''
		D_NEEDS=''
		D_REMOVE=''
		return 1
	fi
	PD_TEXT="$1"
	PD_SEQ="$D_SEQ"
	PD_ALLOW="$D_ALLOW"
	PD_NAMES="$D_NAMES"
	PD_NEEDS="$D_NEEDS"
	PD_REMOVE="$D_REMOVE"
	return 0
}
# --- end of desired.json parser -----------------------------------------

LAST_SEQ=0
if [ -f "$DIR/applied.json" ]; then
	prev="$(<"$DIR/applied.json")"
	[[ "$prev" =~ $RE_SEQ ]] && LAST_SEQ="${BASH_REMATCH[1]}"
fi

# CREATED: "<name> <seq>[ <flag>]" lines (persisted in keyd-created-seq):
# the desired seq at which keyd last created each key, and a flag:
#   p  its result is in results/, not yet taken by the Manager;
#   c  the Manager took the result while desired.json still had
#      needs_secret for it: needs_secret is ignored for the key until a
#      desired.json without it is seen.
SEQFILE="$DIR/keyd-created-seq"
RE_SEQLINE='^(mac-[0-9a-f]{12}-[1-9][0-9]{0,2}) ([0-9]{1,15})( [pc])?$'
CREATED=''
if [ -f "$SEQFILE" ]; then
	while IFS= read -r line || [ -n "$line" ]; do
		[[ "$line" =~ $RE_SEQLINE ]] && CREATED+="$line$nl"
	done <"$SEQFILE"
fi
# created_line name: CL_SEQ and CL_FLAG of name (0 and '' when absent).
created_line() {
	local re="$nl$1 ([0-9]+)( ([pc]))?$nl"
	CL_SEQ=0
	CL_FLAG=''
	if [[ "$nl$CREATED" =~ $re ]]; then
		CL_SEQ="${BASH_REMATCH[1]}"
		CL_FLAG="${BASH_REMATCH[3]}"
	fi
}
save_created() {
	if ! write_atomic "$SEQFILE" "${CREATED%"$nl"}"; then
		SEQ_ERR="keyd-created-seq: $WA_ERR"
		return 1
	fi
	return 0
}
# set_flag name flag: set (or with '' clear) the flag of a recorded name.
set_flag() {
	local line keep='' k
	created_line "$1"
	[ "$CL_FLAG" = "$2" ] && return 0
	while IFS= read -r line; do
		[ -n "$line" ] || continue
		k="${line%% *}"
		if [ "$k" = "$1" ]; then
			line="$k $CL_SEQ${2:+ $2}"
		fi
		keep+="$line$nl"
	done <<<"$CREATED"
	CREATED="$keep"
	save_created
}
# record_created names seq: persist seq for each name, and drop names that
# are neither in MinIO nor desired (names are never reused).
record_created() {
	local names="$1" seq="$2" line k keep=''
	while IFS= read -r line; do
		[ -n "$line" ] || continue
		k="${line%% *}"
		has "$names" "$k" && continue
		{ has "$MANAGED" "$k" || has "$D_NAMES" "$k"; } && keep+="$line$nl"
	done <<<"$CREATED"
	for k in $names; do
		keep+="$k $seq$nl"
	done
	CREATED="$keep"
	save_created
}

# taken_results: names whose result keyd wrote and the Manager has since
# taken. Run BEFORE desired.json is read: a Manager that clears
# needs_secret before it deletes the result is then never misread.
taken_results() {
	local line
	TAKEN=''
	while IFS= read -r line; do
		[[ "$line" =~ $RE_SEQLINE ]] || continue
		[ "${BASH_REMATCH[3]}" = ' p' ] || continue
		[ -e "$DIR/results/${BASH_REMATCH[1]}.json" ] || TAKEN+="${BASH_REMATCH[1]}$nl"
	done <<<"$CREATED"
}
# settle: update the flags from an accepted desired.json.
settle() {
	local line k
	for k in $TAKEN; do
		if has "$D_NEEDS" "$k"; then
			log "$k: the Manager took its result while needs_secret was still set; ignoring needs_secret for it until desired.json clears it (KEYD_PROTOCOL.md)"
			set_flag "$k" c
		else
			set_flag "$k" ''
		fi
	done
	while IFS= read -r line; do
		[[ "$line" =~ $RE_SEQLINE ]] || continue
		[ "${BASH_REMATCH[3]}" = ' c' ] || continue
		has "$D_NEEDS" "${BASH_REMATCH[1]}" || set_flag "${BASH_REMATCH[1]}" ''
	done <<<"$CREATED"
}

# apply: make MinIO match the parsed desired set. Sets ERR on refusal.
apply() {
	local remove='' unknown='' k r e
	for k in $MANAGED; do
		if has "$D_REMOVE" "$k"; then
			remove+="$k$nl"
		elif ! has "$D_NAMES" "$k"; then
			unknown+="$k$nl"
		fi
	done
	if [ -n "$unknown" ]; then
		ERR="preserved $(count "$unknown") unobserved key(s); Manager must report and confirm named orphan removals"
		log "$ERR"
	fi
	r="$(count "$remove")"
	e="$(count "$MANAGED")"
	if [ "$r" -gt 0 ] && { [ "$r" -gt "$MASS_MAX" ] || { [ "$r" -gt 1 ] && [ $((r * 100)) -gt $((MASS_PCT * e)) ]; }; } &&
		[ "${D_ALLOW:-x}" != "$D_SEQ" ]; then
		ERR="REFUSED mass delete of $r of $e keys (set allow_mass_delete to seq $D_SEQ to confirm)"
		log "$ERR"
		return 1
	fi
	# Plan, and record the seq of every create before running any, so a
	# needs_secret request is honoured once per seq even across a crash.
	local fresh='' again=''
	for k in $D_NAMES; do
		if ! has "$EXISTING" "$k"; then
			fresh+="$k$nl"
		elif has "$D_NEEDS" "$k" && [ ! -e "$DIR/results/$k.json" ]; then
			created_line "$k"
			if [ "$D_SEQ" -le "$CL_SEQ" ]; then
				:
			elif [ "$CL_FLAG" = c ]; then
				ERR="needs_secret for $k ignored: it was still set when the Manager took the result of seq $CL_SEQ; clear it in desired.json first"
				log "$ERR"
			else
				again+="$k$nl"
			fi
		fi
	done
	if [ -n "$fresh$again" ] && ! record_created "$fresh$again" "$D_SEQ"; then
		log "cannot write keyd-created-seq ($SEQ_ERR); not re-creating any key this cycle"
		ERR="cannot record created seq: $SEQ_ERR"
		again=''
	fi
	for k in $fresh; do
		create_key "$k" || ERR="${CREATE_ERR:-some keys could not be created}"
	done
	for k in $again; do
		# Crash recovery: the key exists but its secret never reached
		# the Manager. It was never delivered, so re-create it.
		log "re-creating $k: the Manager has no secret for it (seq $D_SEQ)"
		if remove_key "$k"; then
			create_key "$k" || ERR="${CREATE_ERR:-some keys could not be created}"
		else
			ERR="some keys could not be re-created"
		fi
	done
	for k in $remove; do
		remove_key "$k" || ERR="some keys could not be removed"
	done
	return 0
}

write_applied() {
	local names="$MANAGED" k entries='' sep='' err
	[ -n "$SEQ_ERR" ] && [ -z "$ERR" ] && ERR="$SEQ_ERR"
	err="${ERR//[\"\\]/}"
	for k in $D_NAMES; do
		has "$names" "$k" || names+="$k$nl"
	done
	for k in $names; do
		if ! has "$EXISTING" "$k"; then
			entries+="$sep{\"name\":\"$k\",\"exists\":false}"
		elif key_info "$k"; then
			entries+="$sep{\"name\":\"$k\",\"exists\":true,\"status\":\"${I_STATUS//[\"\\]/}\",\"parent\":\"${I_PARENT//[\"\\]/}\",\"implied_policy\":$I_IMPLIED}"
		else
			entries+="$sep{\"name\":\"$k\",\"exists\":true,\"status\":\"unknown\",\"parent\":\"\",\"implied_policy\":false}"
		fi
		sep=','
	done
	write_atomic "$DIR/applied.json" "{\"seq\":$LAST_SEQ,\"verified_ms\":$(now_ms),\"error\":\"$err\",\"keys\":[$entries]}" ||
		log "cannot write applied.json ($WA_ERR)"
}

cycle() {
	local text
	ERR=''
	SEQ_ERR=''
	CREATE_ERR=''
	D_NAMES=''
	D_NEEDS=''
	list_keys || return 1
	taken_results
	if [ -f "$DIR/desired.json" ]; then
		text="$(<"$DIR/desired.json")"
		if [ "$text" != "$PD_TEXT" ] && IFS= read -r -d '' _ <"$DIR/desired.json"; then
			D_ERR='not strict JSON: a NUL byte'
			false
		else
			parse_desired "$text"
		fi
		if [ $? -ne 0 ]; then
			ERR="refused desired.json: $D_ERR"
			D_NAMES=''
			log "$ERR"
		elif [ "$D_SEQ" -lt "$LAST_SEQ" ]; then
			ERR="refused desired.json: seq $D_SEQ is lower than applied seq $LAST_SEQ"
			D_NAMES=''
			log "$ERR"
		else
			settle
			if apply; then
				LAST_SEQ="$D_SEQ"
				list_keys || return 1
			else
				D_NAMES=''
			fi
		fi
	elif [ -d "$DIR/desired.json" ]; then
		ERR="desired.json is a directory"
		log "$ERR"
	fi
	write_applied
}

log "managing service accounts under $PARENT as $KA_AK in $DIR"
while :; do
	cycle
	rc=$?
	[ "$ONCE" = 1 ] && exit "$rc"
	sleep "$INTERVAL" &
	wait $! 2>/dev/null || true
done
