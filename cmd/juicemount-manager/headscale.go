package main

// Headscale supervisor + pairing API (Tier-2 T2.1, JuiceMount Link).
//
// When JM_NET_HEADSCALE=on, the manager runs an embedded Headscale control
// server as a supervised child process:
//
//	headscale serve --config /data/headscale/config.yaml   (listen :8091)
//
// The opt-in overlay server/docker-compose.link.yml publishes host 30193 →
// 8091 (and the NAS node's WireGuard UDP port) so remote Macs reach it; the
// base compose publishes neither while Link is off. Pairing is the consumer
// UX: the manager mints a Tailscale preauth key and hands it to the Mac app,
// which embeds tsnet and joins silently. No accounts, no client installs.
//
// State layout under the manager-state bind mount:
//	/data/headscale/config.yaml   generated once, then user-owned
//	/data/headscale/policy.hujson regenerated by the manager on every start
//	/data/headscale/*.key, db.sqlite   headscale's own state
//
// The control server address is JM_NET_SERVER_URL. The DERP map is
// Headscale's own setting: config.yaml's derp section, or HEADSCALE_DERP_URLS
// / HEADSCALE_DERP_PATHS in the manager's environment, which the child
// inherits.
//
// All /api/net/* routes are admin-key protected by the same middleware as
// the rest of the manager.

import (
	"fmt"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"syscall"
	"time"

	"github.com/lelanddutcher/juicemount/internal/linkconfig"
	"github.com/lelanddutcher/juicemount/internal/manager"
)

const (
	hsListen         = "0.0.0.0:8091" // in-container; docker-compose.link.yml publishes 30193 → 8091
	hsStartupTimeout = 45 * time.Second
	hsStopTimeout    = 10 * time.Second
	// defaultDERPMapURL is Tailscale's public DERP map. Public DERP is
	// fairness-throttled, so it is a last-resort relay, not a video path.
	defaultDERPMapURL = "https://controlplane.tailscale.com/derpmap/default"
)

// hsDataDir and hsBinary are vars (not consts) solely so tests can redirect
// config generation into a temp directory and run a fake or pinned binary.
var (
	hsDataDir = "/data/headscale"
	hsBinary  = "/usr/local/bin/headscale"
)

// headscaleSupervisor owns the child process lifecycle: start, wait for the
// coordination listener, ensure the Link user, then restart with capped
// backoff whenever the child exits or a start attempt fails.
type headscaleSupervisor struct {
	*supervisor
	listen string // the coordination listener the readiness probe dials
}

func newHeadscaleSupervisor() *headscaleSupervisor {
	h := &headscaleSupervisor{listen: hsListen}
	h.supervisor = newSupervisor("headscale", h.runOnce)
	return h
}

func headscaleEnabled() bool { return os.Getenv("JM_NET_HEADSCALE") == "on" }

// externalURL is the address Mac clients must reach for coordination. The
// container only knows its internal listen port, so the operator tells us the
// externally-visible form once: JM_NET_SERVER_URL (e.g.
// https://nas.example.com:30193). Without it, pairing is refused with a clear
// error rather than minting keys that point at an unreachable address.
func externalURL() string { return strings.TrimRight(os.Getenv("JM_NET_SERVER_URL"), "/") }

// tlsConfigBlock renders the headscale TLS stanza for operator-provided
// certificates (headscale v0.29 "bring your own certificate" mode —
// tls_cert_path/tls_key_path in config-example.yaml). ACME is deliberately
// NOT used: it needs port 80 + a public name, which a home NAS rarely has.
// An empty result means "no TLS" (plain HTTP on listen_addr, today's
// behavior).
//
// DEPLOYMENT (T2.4): mount the PEM cert (full chain) and key into the
// manager container, then set before FIRST generation:
//
//	JM_NET_TLS_CERT=/data/tls/fullchain.pem
//	JM_NET_TLS_KEY=/data/tls/privkey.pem
//	JM_NET_SERVER_URL=https://<public-name-or-ip>:30193   # must match the cert
//
// config.yaml is generated once and then user-owned, so changing these env
// vars later requires deleting /data/headscale/config.yaml to regenerate.
// With TLS on, headscale serves HTTPS on the same listen_addr; Mac clients
// pair against the https:// server_url, and tsnet verifies the certificate
// against the system trust store.
func tlsConfigBlock(certPath, keyPath string) string {
	if certPath == "" || keyPath == "" {
		return ""
	}
	return fmt.Sprintf("tls_cert_path: %s\ntls_key_path: %s\n", certPath, keyPath)
}

// headscaleConfigParams is everything the generated config.yaml varies on.
type headscaleConfigParams struct {
	ServerURL     string
	Listen        string
	MetricsListen string
	GRPCListen    string
	DataDir       string
	TLSBlock      string
	DERPURLs      []string
	DERPPaths     []string
}

func renderHeadscaleConfig(p headscaleConfigParams) string {
	derp := "  urls:"
	if len(p.DERPURLs) == 0 {
		derp += " []"
	}
	derp += "\n"
	for _, u := range p.DERPURLs {
		derp += "    - " + u + "\n"
	}
	if len(p.DERPPaths) > 0 {
		derp += "  paths:\n"
		for _, path := range p.DERPPaths {
			derp += "    - " + path + "\n"
		}
	}
	return fmt.Sprintf(`server_url: %s
listen_addr: %s
metrics_listen_addr: %s
grpc_listen_addr: %s
private_key_path: %[5]s/node.key
noise:
  private_key_path: %[5]s/noise_private.key
prefixes:
  v4: 100.64.0.0/10
  v6: fd7a:115c:a1e0::/48
  allocation: sequential
dns:
  magic_dns: false
  base_domain: jum.local
  override_local_dns: false
  nameservers:
    global: []
    split: {}
derp:
  server:
    enabled: false
%[7]s  auto_update_enabled: true
database:
  type: sqlite
  sqlite:
    path: %[5]s/db.sqlite
log:
  level: info
%[6]sunix_socket: %[5]s/headscale.sock
unix_socket_permission: "0770"
# The ACL policy is not set here: juicemount-manager regenerates
# policy.hujson on every start and passes it as HEADSCALE_POLICY_PATH.
# A top-level policy: stanza added here takes precedence and the
# manager then leaves the policy and node tags to you.
`, p.ServerURL, p.Listen, p.MetricsListen, p.GRPCListen, p.DataDir, p.TLSBlock, derp)
}

func ensureConfig() (string, error) {
	cfgPath := filepath.Join(hsDataDir, "config.yaml")
	publicURL := externalURL()
	certPath, keyPath := os.Getenv("JM_NET_TLS_CERT"), os.Getenv("JM_NET_TLS_KEY")
	if err := validateLinkTransport(publicURL, certPath, keyPath,
		os.Getenv("JM_NET_ALLOW_INSECURE") == "1",
		os.Getenv("JM_NET_ALLOW_LAN_ONLY") == "1"); err != nil {
		return "", err
	}
	if _, err := os.Stat(cfgPath); err == nil {
		if err := validatePersistedLinkConfig(cfgPath, publicURL, certPath, keyPath); err != nil {
			return "", err
		}
		return cfgPath, nil
	} else if !os.IsNotExist(err) {
		return "", fmt.Errorf("inspect persisted Headscale config: %w", err)
	}
	if err := os.MkdirAll(hsDataDir, 0o755); err != nil {
		return "", err
	}
	cfg := renderHeadscaleConfig(headscaleConfigParams{
		ServerURL:     publicURL,
		Listen:        hsListen,
		MetricsListen: "127.0.0.1:9091",
		GRPCListen:    "127.0.0.1:50443",
		DataDir:       hsDataDir,
		TLSBlock:      tlsConfigBlock(certPath, keyPath),
		DERPURLs:      []string{defaultDERPMapURL},
	})
	if err := os.WriteFile(cfgPath, []byte(cfg), 0o600); err != nil {
		return "", err
	}
	return cfgPath, nil
}

// headscaleServeEnv returns the extra environment for `headscale serve`.
// When the Manager owns the policy it writes policy.hujson and points
// Headscale at it through Headscale's own config environment, which also
// reaches installs whose user-owned config.yaml predates the policy.
func headscaleServeEnv(cfgPath string) ([]string, error) {
	if !manager.LinkPolicyManaged(cfgPath) {
		return nil, nil
	}
	path, err := writeLinkPolicy(cfgPath)
	if err != nil {
		return nil, fmt.Errorf("write Link ACL policy: %w", err)
	}
	return []string{"HEADSCALE_POLICY_MODE=file", "HEADSCALE_POLICY_PATH=" + path}, nil
}

// validatePersistedLinkConfig prevents an env-only URL/TLS change from being
// advertised by the pairing API while Headscale continues serving its old
// generated configuration. The identity database and keys are durable; only
// config.yaml needs regeneration after an intentional transport change.
func validatePersistedLinkConfig(cfgPath, publicURL, certPath, keyPath string) error {
	raw, err := os.ReadFile(cfgPath)
	if err != nil {
		return fmt.Errorf("read persisted Headscale config: %w", err)
	}
	cfg := string(raw)
	wantServer := "server_url: " + publicURL
	if !hasExactConfigLine(cfg, wantServer) {
		return fmt.Errorf("persisted Headscale config does not match JM_NET_SERVER_URL %q; stop Manager and remove only %s (preserve db.sqlite and key files), then redeploy to regenerate it", publicURL, cfgPath)
	}
	hasCert := hasConfigKey(cfg, "tls_cert_path:")
	hasKey := hasConfigKey(cfg, "tls_key_path:")
	if certPath == "" {
		if hasCert || hasKey {
			return fmt.Errorf("persisted Headscale config still enables TLS while JM_NET_TLS_CERT/JM_NET_TLS_KEY are empty; regenerate only %s", cfgPath)
		}
		return nil
	}
	if !hasExactConfigLine(cfg, "tls_cert_path: "+certPath) ||
		!hasExactConfigLine(cfg, "tls_key_path: "+keyPath) {
		return fmt.Errorf("persisted Headscale TLS paths do not match JM_NET_TLS_CERT/JM_NET_TLS_KEY; regenerate only %s", cfgPath)
	}
	return nil
}

func hasExactConfigLine(cfg, want string) bool {
	for _, line := range strings.Split(cfg, "\n") {
		if strings.TrimSpace(line) == want {
			return true
		}
	}
	return false
}

func hasConfigKey(cfg, key string) bool {
	for _, line := range strings.Split(cfg, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), key) {
			return true
		}
	}
	return false
}

func validateLinkTransport(raw, certPath, keyPath string, allowInsecure, allowLANOnly bool) error {
	if err := linkconfig.ValidateServerURL(raw, allowInsecure, allowLANOnly); err != nil {
		return err
	}
	u, _ := linkconfig.ParseServerURL(raw)
	if (certPath == "") != (keyPath == "") {
		return fmt.Errorf("JM_NET_TLS_CERT and JM_NET_TLS_KEY must be configured together")
	}
	if certPath != "" && u.Scheme != "https" {
		return fmt.Errorf("JM_NET_SERVER_URL must use https when Link TLS certificates are configured")
	}
	return nil
}

// runOnce is one supervised start: launch the child, wait for its
// coordination listener, create the Link user, then report ready and block
// until the child exits. A live PID is not sufficient: the old behavior
// declared success while Headscale was still booting (or while user creation
// had failed), so the UI issued pairing codes that could never register a
// Mac.
func (h *headscaleSupervisor) runOnce(stop <-chan struct{}, ready func(string)) error {
	cfg, err := ensureConfig()
	if err != nil {
		return err
	}
	env, err := headscaleServeEnv(cfg)
	if err != nil {
		return err
	}
	cmd := exec.Command(hsBinary, "serve", "--config", cfg)
	cmd.Env = append(os.Environ(), env...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("headscale start: %w", err)
	}
	exited := make(chan struct{})
	var waitErr error
	go func() {
		waitErr = cmd.Wait()
		close(exited)
	}()
	terminate := func() {
		_ = cmd.Process.Signal(syscall.SIGTERM)
		select {
		case <-exited:
		case <-time.After(hsStopTimeout):
			_ = cmd.Process.Kill()
			<-exited
		}
	}
	// A cold Headscale start opens and validates its durable SQLite state
	// before binding the coordination listener. The release NAS measured just
	// over the old ten-second budget while its ZFS pool was busy, so a healthy
	// child was killed and Link stayed disabled until the whole Manager was
	// restarted. Keep startup bounded, but leave enough room for real storage
	// latency rather than treating it as a control-plane failure.
	if err := waitForHeadscaleListener(h.listen, hsStartupTimeout, stop, exited); err != nil {
		terminate()
		if isClosed(exited) && waitErr != nil {
			return fmt.Errorf("%w (headscale exited: %v)", err, waitErr)
		}
		return err
	}
	if err := ensureHeadscaleUser(cfg); err != nil {
		terminate()
		return err
	}
	ready("coordination listener " + h.listen)
	select {
	case <-stop:
		terminate()
		return errStopped
	case <-exited:
		return fmt.Errorf("headscale exited: %v", waitErr)
	}
}

func isClosed(ch <-chan struct{}) bool {
	select {
	case <-ch:
		return true
	default:
		return false
	}
}

func waitForHeadscaleListener(listen string, timeout time.Duration, stop, exited <-chan struct{}) error {
	_, port, err := net.SplitHostPort(listen)
	if err != nil {
		return fmt.Errorf("headscale listener config %q: %w", listen, err)
	}
	deadline := time.Now().Add(timeout)
	var lastErr error
	for time.Now().Before(deadline) {
		conn, err := net.DialTimeout("tcp", net.JoinHostPort("127.0.0.1", port), 250*time.Millisecond)
		if err == nil {
			_ = conn.Close()
			return nil
		}
		lastErr = err
		select {
		case <-stop:
			return errStopped
		case <-exited:
			return fmt.Errorf("headscale exited before listening")
		case <-time.After(200 * time.Millisecond):
		}
	}
	return fmt.Errorf("headscale did not listen within %s: %w", timeout, lastErr)
}

func ensureHeadscaleUser(cfg string) error {
	var lastErr error
	for tries := 0; tries < 10; tries++ {
		out, err := exec.Command(hsBinary, "--config", cfg, "users", "create", manager.LinkUserName()).CombinedOutput()
		if err == nil || headscaleUserAlreadyExists(string(out)) {
			return nil
		}
		lastErr = fmt.Errorf("%v: %s", err, strings.TrimSpace(string(out)))
		time.Sleep(500 * time.Millisecond)
	}
	return fmt.Errorf("headscale user setup failed: %w", lastErr)
}

// headscaleUserAlreadyExists recognises the two forms emitted by supported
// Headscale versions when `users create jm` is repeated. Older releases say
// "already exists"; newer gRPC-backed releases surface SQLite's unique-key
// violation instead. Both mean the desired durable Link user is ready.
func headscaleUserAlreadyExists(out string) bool {
	s := strings.ToLower(out)
	return strings.Contains(s, "already exists") ||
		(strings.Contains(s, "unique constraint failed") && strings.Contains(s, "users.name"))
}
