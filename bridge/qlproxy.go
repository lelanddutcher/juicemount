// QLPROXY (T1.1/F4/F5) — Quick Look proxy plane, bridge side.
//
// Two pieces live here:
//
//  1. GET /ql-preview?path=<abs> — the spacebar-plays-BRAW serving endpoint.
//     A Quick Look preview extension resolves the user-facing path of a RAW
//     clip to its kind="qlpreview" sidecar asset (short faststart H.264 MP4,
//     generated by jmfarm -ql-preview) and plays THAT, never the source.
//     Local-cache-first (hit <5ms), bounded read-through populate on miss,
//     404-fast otherwise so macOS falls back gracefully. Mirrors the proven
//     /thumb-local contract one lane over (bridge/thumbs.go).
//
//  2. F5 hot-project prewarm — on a LAN-class link (or an explicit trigger),
//     hydrate poster thumbnails + QL-preview blobs for the most recently
//     modified project into the local persistent thumb cache BEFORE the user
//     leaves the desk, so offline/spacebar work costs zero network.
//
// Everything decision-shaped below takes its dependencies injected, so the
// core is unit-testable against fakes exactly like serveThumbLocal.

// qlKind is the derivative kind served by /ql-preview and hydrated by the
// prewarm pass. Same wire string as farm.QLPreviewKind.
const qlKind = farm.QLPreviewKind

// qlMediaType is the pinned Content-Type for kind "qlpreview" — mirrors
// blobMediaTypes in internal/farm/sidecar.go, which is the single authority.
const qlMediaType = "video/mp4"

// qlReadThroughCap bounds the read-through populate of ONE preview blob.
// A capped 960px/20s veryfast encode lands around 3-8MB; anything claiming to
// be far larger is refused rather than pulled onto the local SSD.
const qlReadThroughCap = 32 << 20

// ---------------------------------------------------------------------------
// /ql-preview — the Quick Look preview endpoint
// ---------------------------------------------------------------------------

// qlDeps is the injected surface of serveQLPreview (thumbLocalDeps' sibling).
type qlDeps struct {
	mount     string                                          // configured user-facing mount point ("/Volumes/zpool")
	lookup    func(rel string) (inode uint64, isDir, ok bool) // RAM mirror path→inode
	cachePath func(inode uint64) (root, rel string, ok bool)  // local cached blob (root+rel: anchored serve)
	populate  func(inode uint64) (root, rel string, ok bool)  // read-through resolve+cache
	warmDir   func(relDir string)                             // async dir warm (posters), best-effort
}

// serveQLPreview answers GET /ql-preview?path=<abs>. Contract with the appex:
//   - 200 video/mp4 → playable proxy bytes; http.ServeContent provides the
//     full Range/206 contract AVPlayer needs to seek.
//   - 404 (fast)    → the appex reports failure and macOS falls back; we kick
//     an async poster warm so the thumbnail plane still improves.
func serveQLPreview(w http.ResponseWriter, r *http.Request, d qlDeps) {
	p := r.URL.Query().Get("path")
	if p == "" || !filepath.IsAbs(p) {
		http.Error(w, "path (absolute) required", http.StatusBadRequest)
		return
	}
	p = filepath.Clean(p)
	if d.mount == "" || d.lookup == nil || d.cachePath == nil ||
		(p != d.mount && !strings.HasPrefix(p, d.mount+"/")) {
		w.Header().Set("X-JM-QL", "outside-mount")
		http.NotFound(w, r)
		return
	}
	rel := strings.TrimPrefix(strings.TrimPrefix(p, d.mount), "/")
	if rel == "" || metadata.ScanFilteredPath(rel) {
		w.Header().Set("X-JM-QL", "filtered")
		http.NotFound(w, r)
		return
	}
	inode, isDir, ok := d.lookup(rel)
	if !ok || isDir {
		w.Header().Set("X-JM-QL", "unknown-path")
		http.NotFound(w, r)
		return
	}
	// ANCHORED serve, identical discipline to /thumb-local: open through the
	// split root+rel pair so no component can be swapped for a symlink after
	// the cache answered.
	serve := func(root, rel, label string) bool {
		f, err := derivatives.OpenRegularUnder(root, rel)
		if err != nil {
			return false
		}
		defer f.Close()
		fi, serr := f.Stat()
		if serr != nil {
			return false
		}
		w.Header().Set("Content-Type", qlMediaType)
		w.Header().Set("X-JM-QL", label)
		w.Header().Set("Cache-Control", "no-store")
		http.ServeContent(w, r, "", fi.ModTime(), f)
		return true
	}
	if root, rel, ok := d.cachePath(inode); ok {
		if serve(root, rel, "hit") {
			return
		}
	}
	if d.populate != nil {
		if root, rel, ok := d.populate(inode); ok {
			if serve(root, rel, "populated") {
				return
			}
		}
	}
	if d.warmDir != nil {
		d.warmDir(path.Dir(rel))
	}
	w.Header().Set("X-JM-QL", "miss")
	http.NotFound(w, r)
}

// resolveDerivBlobPath resolves an inode's READY blob row of ANY kind to its
// absolute-on-FUSE location — the generic form of resolveThumbBlobPath
// (bridge/thumbs.go), which stays untouched because the warmer depends on its
// exact shape. Same chain: Tier-B index first, then the JM-15 one-sidecar
// reconcile for a farm-derived asset not yet ingested, then the C5 freshness
// gate against the RAM mirror before any bytes are named.
func resolveDerivBlobPath(ds *derivatives.Store, mount string, inode uint64, kind string) (mountOut, blobRel string, ok bool) {
	if ds == nil || mount == "" {
		return "", "", false
	}
	if known, _ := ds.Known(inode); !known {
		if found, ferr := farm.ReconcileOneSidecar(ds, mount, inode); ferr != nil || !found {
			return "", "", false
		}
	}
	rows, err := ds.Manifest(inode)
	if err != nil {
		return "", "", false
	}
	for _, d := range rows {
		if d.Kind != kind || d.Status != "ready" || d.BlobRelPath == nil || *d.BlobRelPath == "" {
			continue
		}
		live := liveSourceFor(inode)
		if derivRowStale(d, live) {
			rejectStaleDeriv(globalThumbCache, inode, kind, d, live)
			return "", "", false
		}
		return mount, derivatives.DerivBlobRel(inode, *d.BlobRelPath), true
	}
	return "", "", false
}

// populateDerivFromFUSE reads one derivative blob from FUSE into the local
// thumb cache under (inode, kind) and returns the CACHE path to serve from.
// Size-capped and anchored-open (O_NOFOLLOW every component) — the same guard
// set populateThumbFromFUSE applies, generalized over kinds.
func populateDerivFromFUSE(tc *thumbcache.Cache, ds *derivatives.Store, mount string, inode uint64, kind string, capBytes int64) (root, rel string, ok bool) {
	if tc == nil {
		return "", "", false
	}
	fmount, blobRel, ok := resolveDerivBlobPath(ds, mount, inode, kind)
	if !ok {
		return "", "", false
	}
	f, err := derivatives.OpenRegularUnder(fmount, blobRel)
	if err != nil {
		return "", "", false
	}
	defer f.Close()
	fi, err := f.Stat()
	if err != nil || fi.Size() <= 0 || fi.Size() > capBytes {
		return "", "", false
	}
	if _, err := tc.Put(inode, kind, f); err != nil {
		return "", "", false
	}
	return tc.PathParts(inode, kind)
}

// handleQLPreviewHTTP wires serveQLPreview to the live bridge globals.
func handleQLPreviewHTTP(w http.ResponseWriter, r *http.Request) {
	globalMu.Lock()
	rc := globalRC
	tc := globalThumbCache
	ds := globalDerivStore
	warmer := globalThumbWarmer
	mount := globalWantMountPoint
	fuseMount := globalFUSEPath
	if fuseMount == "" {
		fuseMount = globalMountPath
	}
	globalMu.Unlock()
	if rc == nil || tc == nil {
		http.Error(w, "not ready", http.StatusServiceUnavailable)
		return
	}
	serveQLPreview(w, r, qlDeps{
		mount: mount,
		lookup: func(rel string) (uint64, bool, bool) {
			e := rc.Store().LookupByPath(rel)
			if e == nil {
				return 0, false, false
			}
			return e.Inode, e.IsDir, true
		},
		cachePath: func(ino uint64) (string, string, bool) {
			// C5 freshness gate on cache hits, exactly like freshThumbCachePath:
			// the persistent cache is read BEFORE any manifest lookup, so a
			// stale preview would otherwise be served straight off local disk.
			croot, crel, ok := freshThumbCacheKindPath(ds, tc, ino, qlKind)
			return croot, crel, ok
		},
		populate: func(ino uint64) (string, string, bool) {
			return populateDerivFromFUSE(tc, ds, fuseMount, ino, qlKind, qlReadThroughCap)
		},
		warmDir: func(relDir string) {
			if warmer != nil {
				warmer.WarmDirAsync(relDir)
			}
		},
	})
}

// freshThumbCacheKindPath is freshThumbCachePath (bridge/thumbs.go)
// generalized over kinds: cache-hit lookup + C5 staleness rejection for any
// derivative kind held in the thumb cache.
func freshThumbCacheKindPath(ds *derivatives.Store, tc *thumbcache.Cache, inode uint64, kind string) (root, rel string, ok bool) {
	if tc == nil {
		return "", "", false
	}
	croot, crel, ok := tc.PathParts(inode, kind)
	if !ok {
		return "", "", false
	}
	if ds == nil {
		return croot, crel, true
	}
	rows, err := ds.Manifest(inode)
	if err != nil {
		return croot, crel, true // index unreadable — no basis to reject; serve.
	}
	for _, d := range rows {
		if d.Kind != kind || d.Status != "ready" {
			continue
		}
		live := liveSourceFor(inode)
		if derivRowStale(d, live) {
			rejectStaleDeriv(tc, inode, kind, d, live)
			return "", "", false
		}
		break
	}
	return croot, crel, true
}

