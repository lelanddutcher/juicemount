// Tuning. The pass is background work: budgets keep it off the interactive
// lane, the cooldown keeps it off the metered bill, and the whole thing dies
// instantly when offline.
const (
	qlPrewarmPollInterval = 60 * time.Second // LAN-class poll cadence
	qlPrewarmCooldown     = 30 * time.Minute // min gap between AUTO passes
	qlPrewarmFileBudget   = 200              // newest files hydrated per pass
	qlPrewarmScanBudget   = 250_000          // max mirror entries walked per pass
	qlThumbBlobCap        = 2 << 20          // poster size cap (matches thumbWarmBlobCap)
	qlPrewarmConcurrency  = 2                // parallel hydration workers
)

// qlMediaExts gates which mirrored files count as preview-worthy. Extension
// check only — the derivative manifest is the real arbiter later.
var qlMediaExts = map[string]bool{
	".mov": true, ".mp4": true, ".m4v": true, ".mxf": true, ".mkv": true,
	".avi": true, ".mts": true, ".m2ts": true, ".braw": true, ".r3d": true,
	".wav": true, ".aif": true, ".aiff": true, ".flac": true, ".mp3": true, ".m4a": true,
}

// qlPrewarmStats is the observable state of the prewarm engine (GET /prewarm).
type qlPrewarmStats struct {
	Busy             bool   `json:"busy"`
	LastRunUnix      int64  `json:"last_run_unix"`
	LastTrigger      string `json:"last_trigger"` // "" | "lan" | "manual"
	LastDir          string `json:"last_dir"`
	FilesConsidered  int    `json:"files_considered"`
	ThumbsHydrated   int    `json:"thumbs_hydrated"`
	PreviewsHydrated int    `json:"previews_hydrated"`
	Errors           int    `json:"errors"`
	Note             string `json:"note,omitempty"`
}

var qlPrewarm struct {
	mu      sync.Mutex
	stats   qlPrewarmStats
	started bool
}

func qlStatsSnapshot() qlPrewarmStats {
	qlPrewarm.mu.Lock()
	defer qlPrewarm.mu.Unlock()
	return qlPrewarm.stats
}

func qlStatsSet(fn func(s *qlPrewarmStats)) {
	qlPrewarm.mu.Lock()
	defer qlPrewarm.mu.Unlock()
	fn(&qlPrewarm.stats)
}

// startQLPrewarm launches the LAN-class watcher once per process. Called from
// NFSServerStart (marked // QLPROXY there); safe across Stop/Start cycles —
// the loop re-reads the globals every tick, so a torn-down session simply
// no-ops until the next Start republishes them. JM_QL_PREWARM=0 disables the
// poller (the manual /prewarm trigger keeps working).
func startQLPrewarm() {
	qlPrewarm.mu.Lock()
	already := qlPrewarm.started
	qlPrewarm.started = true
	qlPrewarm.mu.Unlock()
	if already {
		return
	}
	if os.Getenv("JM_QL_PREWARM") == "0" {
		jmlog.Info("ql prewarm: LAN watcher disabled (JM_QL_PREWARM=0)")
		return
	}
	go qlPrewarmLoop()
	jmlog.Info("ql prewarm: LAN watcher armed",
		"poll", qlPrewarmPollInterval.String(), "cooldown", qlPrewarmCooldown.String())
}

// qlPrewarmLoop watches the measured link class and fires an automatic pass
// when the Mac is on a FAST link (netprofile ClassFast: >~200 MB/s — 10GbE/
// LAN). This is deliberately the MEASURED signal, not an env knob and not an
// interface-name heuristic: it can only say "fast" after real traffic proved
// the link fast, which is exactly the "before leaving the desk" condition F5
// wants. A cooldown bounds repeat passes while a long session holds the class.
func qlPrewarmLoop() {
	t := time.NewTicker(qlPrewarmPollInterval)
	defer t.Stop()
	for range t.C {
		globalMu.Lock()
		alive := globalRC != nil && globalStore != nil && globalThumbCache != nil
		globalMu.Unlock()
		if !alive || pin.IsOffline() {
			continue
		}
		st := qlStatsSnapshot()
		if st.Busy {
			continue
		}
		if st.LastTrigger == "lan" && time.Since(time.Unix(st.LastRunUnix, 0)) < qlPrewarmCooldown {
			continue
		}
		if netprofile.Default().Class() != netprofile.ClassFast {
			continue
		}
		go func() {
			n := runQLPrewarmPass("", "lan")
			jmlog.Info("ql prewarm: LAN pass complete", "hydrated", n)
		}()
	}
}

// qlChild is one mirror child the prewarm core consumes (decoupled from
// metadata.Entry so tests can build tiny fake trees).
type qlChild struct {
	Inode uint64
	Path  string
	Name  string
	IsDir bool
	Mtime time.Time
	Size  int64
}

// qlTree is the injected filesystem view of the prewarm core.
type qlTree struct {
	children func(dir string) []qlChild
}

// collectMedia walks dir depth-first within the scan budget and returns the
// media files found, NEWEST first. Recursion is bounded by qlMaxWalkDepth —
// shoot folders are shallow; a pathological tree simply truncates its tail.
const qlMaxWalkDepth = 6

func (t qlTree) collectMedia(dir string) []qlChild {
	var out []qlChild
	budget := qlPrewarmScanBudget
	var walk func(d string, depth int)
	walk = func(d string, depth int) {
		if budget <= 0 || depth > qlMaxWalkDepth {
			return
		}
		for _, k := range t.children(d) {
			budget--
			if budget <= 0 {
				return
			}
			if k.IsDir {
				if strings.HasPrefix(k.Name, ".") {
					continue
				}
				walk(k.Path, depth+1)
				continue
			}
			if k.Inode == 0 || strings.HasPrefix(k.Name, "._") || strings.HasPrefix(k.Name, ".") {
				continue
			}
			if !qlMediaExts[strings.ToLower(filepath.Ext(k.Name))] {
				continue
			}
			out = append(out, k)
		}
	}
	walk(dir, 0)
	sort.Slice(out, func(i, j int) bool { return out[i].Mtime.After(out[j].Mtime) })
	return out
}

// hotProjectDir picks the volume's "hot project": the TOP-LEVEL directory whose
// subtree contains the single most recently modified entry. All reads are RAM
// mirror lookups (~µs each) — never a backend call — so even a large tree
// costs milliseconds. Falls back to the root itself when the top level holds
// loose media rather than project folders.
func (t qlTree) hotProjectDir() string {
	kids := t.children(".")
	type cand struct {
		dir      string
		newest   time.Time
		hasMedia bool
	}
	var best cand
	root := cand{dir: "."}
	for _, k := range kids {
		if !k.IsDir || strings.HasPrefix(k.Name, ".") {
			if !k.IsDir && qlMediaExts[strings.ToLower(filepath.Ext(k.Name))] && k.Mtime.After(root.newest) {
				root.newest = k.Mtime
				root.hasMedia = true
			}
			continue
		}
		files := t.collectMedia(k.Path)
		if len(files) == 0 {
			continue
		}
		if files[0].Mtime.After(best.newest) {
			best = cand{dir: k.Path, newest: files[0].Mtime, hasMedia: true}
		}
	}
	switch {
	case best.hasMedia && (!root.hasMedia || best.newest.After(root.newest)):
		return best.dir
	case root.hasMedia:
		return root.dir
	default:
		return ""
	}
}

// hydrateOne pulls one (inode, kind) blob into the local thumb cache through
// the prefetch-class bulk lane (sheds under contention — interactive wins).
func hydrateOne(tc *thumbcache.Cache, ds *derivatives.Store, fuseMount string, inode uint64, kind string, capBytes int64) (bool, error) {
	if tc.Has(inode, kind) {
		return false, nil
	}
	release, admitted := jmnfs.TryAcquireBulkRead()
	if !admitted {
		return false, nil // shed: try again next pass
	}
	defer release()
	root, _, ok := populateDerivFromFUSE(tc, ds, fuseMount, inode, kind, capBytes)
	return ok && root != "", nil
}

// runQLPrewarmPass hydrates posters + QL previews for the newest media under
// dir ("" → auto-detect the hot project). Synchronous; callers wrap in a
// goroutine. Returns the number of blobs newly hydrated.
func runQLPrewarmPass(dir string, trigger string) int {
	qlPrewarm.mu.Lock()
	if qlPrewarm.stats.Busy {
		qlPrewarm.mu.Unlock()
		return 0
	}
	qlPrewarm.stats.Busy = true
	qlPrewarm.mu.Unlock()
	defer qlStatsSet(func(s *qlPrewarmStats) { s.Busy = false })

	// Globals are re-read at run time so Stop/Start cycles can't strand us on
	// closed handles.
	globalMu.Lock()
	rc := globalRC
	tc := globalThumbCache
	ds := globalDerivStore
	fuseMount := globalFUSEPath
	if fuseMount == "" {
		fuseMount = globalMountPath
	}
	globalMu.Unlock()
	if rc == nil || tc == nil || ds == nil {
		qlStatsSet(func(s *qlPrewarmStats) { s.Note = "not ready" })
		return 0
	}
	store := rc.Store()

	tree := qlTree{children: func(d string) []qlChild {
		kids, err := store.ListChildren(d)
		if err != nil {
			return nil
		}
		out := make([]qlChild, 0, len(kids))
		for _, e := range kids {
			out = append(out, qlChild{Inode: e.Inode, Path: e.Path, Name: e.Name,
				IsDir: e.IsDir, Mtime: e.Mtime, Size: e.Size})
		}
		return out
	}}

	if dir == "" {
		dir = tree.hotProjectDir()
	}
	if dir == "" || metadata.ScanFilteredPath(dir) {
		qlStatsSet(func(s *qlPrewarmStats) { s.Note = "no hot project found" })
		return 0
	}
	files := tree.collectMedia(dir)
	if len(files) > qlPrewarmFileBudget {
		files = files[:qlPrewarmFileBudget]
	}

	qlStatsSet(func(s *qlPrewarmStats) {
		s.LastRunUnix = time.Now().Unix()
		s.LastTrigger = trigger
		s.LastDir = dir
		s.FilesConsidered = len(files)
		s.Note = ""
	})
	if pin.IsOffline() {
		qlStatsSet(func(s *qlPrewarmStats) { s.Note = "offline — pass aborted" })
		return 0
	}

	sem := make(chan struct{}, qlPrewarmConcurrency)
	var wg sync.WaitGroup
	var mu sync.Mutex
	errs := 0
	for _, f := range files {
		if pin.IsOffline() {
			break
		}
		wg.Add(1)
		go func(f qlChild) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			localErrs := 0
			if ok, herr := hydrateOne(tc, ds, fuseMount, f.Inode, "thumbnail", qlThumbBlobCap); herr != nil {
				localErrs++
			} else if ok {
				qlStatsSet(func(s *qlPrewarmStats) { s.ThumbsHydrated++ })
			}
			if ok, herr := hydrateOne(tc, ds, fuseMount, f.Inode, qlKind, qlReadThroughCap); herr != nil {
				localErrs++
			} else if ok {
				qlStatsSet(func(s *qlPrewarmStats) { s.PreviewsHydrated++ })
			}
			if localErrs > 0 {
				mu.Lock()
				errs += localErrs
				mu.Unlock()
			}
		}(f)
	}
	wg.Wait()
	qlStatsSet(func(s *qlPrewarmStats) { s.Errors += errs })
	jmlog.Info("ql prewarm: pass done",
		"trigger", trigger, "dir", dir, "files", len(files),
		"thumbs", qlStatsSnapshot().ThumbsHydrated, "previews", qlStatsSnapshot().PreviewsHydrated)
	n := qlStatsSnapshot().PreviewsHydrated + qlStatsSnapshot().ThumbsHydrated
	return n
}

// handlePrewarmHTTP serves GET /prewarm (status JSON) and accepts an explicit
// trigger — GET or POST with ?run=1, optionally ?path=<abs dir> to scope the
// pass (default: auto-detected hot project). GET-mutation matches the
// /offline?on=… / /spool-recover convention on this control plane.
func handlePrewarmHTTP(w http.ResponseWriter, r *http.Request) {
	if r.URL.Query().Get("run") == "1" {
		dir := ""
		if p := r.URL.Query().Get("path"); p != "" {
			p = filepath.Clean(p)
			globalMu.Lock()
			mount := globalWantMountPoint
			globalMu.Unlock()
			if !filepath.IsAbs(p) || mount == "" ||
				(p != mount && !strings.HasPrefix(p, mount+"/")) {
				http.Error(w, "path outside mount", http.StatusBadRequest)
				return
			}
			dir = strings.TrimPrefix(strings.TrimPrefix(p, mount), "/")
		}
		go func() { runQLPrewarmPass(dir, "manual") }()
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(map[string]any{"started": true, "dir": dir})
		return
	}
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(qlStatsSnapshot())
}
